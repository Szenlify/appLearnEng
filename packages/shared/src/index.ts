import { z } from 'zod';

export type CEFRLevel = 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2';

export interface TranslationResponse {
  hash: string;                         // SHA-256 hash
  target_language: string;              // 'pl', 'de', 'es', 'fr', 'it', 'ja', etc.
  selected_text: string;                // The exact word or phrase tapped
  lemma: string;                        // Base dictionary form
  part_of_speech: string;               // e.g. "phrasal verb", "verb", "idiom", "noun"
  ipa: string;                          // Phonetic pronunciation, e.g. "/ˌpʊt ʌp ˈwɪð/"
  cefr_level: CEFRLevel;
  simple_definition: string;            // Simple, concise definition in user's native language
  contextual_translation: string;       // Precise translation of word in this context
  sentence_translation: string;         // Full sentence translation in native language
  context_explanation: string;          // In-depth explanation ("Explain in context")
  example_sentence_en: string;          // Alternative English example
  example_sentence_native: string;      // Native language translation of the example
  created_at: string;                   // ISO 8601 timestamp
}

export interface SubtitleCue {
  id: string;             // Unique cue ID, e.g. "cue_0"
  start: number;          // In seconds (e.g. 14.25)
  duration: number;       // In seconds (e.g. 2.40)
  end: number;            // In seconds (start + duration)
  text: string;           // Full raw sentence: "I can't put up with this attitude."
  tokens: string[];       // Tokenized words: ["I", "can't", "put", "up", "with", "this", "attitude."]
}

export interface CaptionsResponse {
  videoId: string;
  language: string;       // e.g. "en" or "a.en"
  isAutoGenerated: boolean;
  cues: SubtitleCue[];
}

export interface SearchVideoItem {
  id: string;                 // YouTube Video ID (np. "kJQP7kiw5Fk")
  title: string;
  channelTitle: string;
  thumbnailUrl: string;
  duration?: string;          // np. "14:20"
  publishedAt?: string;       // ISO 8601 string
  hasCaptions?: boolean;      // flaga dostępności napisów
}

export interface SearchResponse {
  query: string;
  items: SearchVideoItem[];
  nextPageToken?: string;
  cached: boolean;
}

export interface TranslateRequestBody {
  word: string;
  sentence: string;
  targetLang: string; // e.g. 'pl', 'de', 'es', 'fr', 'ja'
  videoId?: string;
  userId?: string;
}

export interface Flashcard {
  id: string;
  user_id: string;
  type: 'word' | 'sentence';
  target_text: string;           // Word ("put up with") OR Sentence ("I can't put up with this.")
  translation: string;           // Native translation
  simple_definition?: string;    // Simple definition in native language
  context_sentence?: string;     // Source sentence from video
  context_explanation?: string;  // "Explain in context" details
  lemma?: string;
  part_of_speech?: string;
  ipa?: string;
  cefr_level?: CEFRLevel;
  r2_cache_hash?: string;
  video_id?: string;
  video_timestamp_sec?: number;
  repetitions: number;
  interval_days: number;
  ease_factor: number;
  next_review_at: string;        // ISO 8601 timestamp
  created_at?: string;
  updated_at?: string;
}

export interface CreateFlashcardRequestBody {
  type: 'word' | 'sentence';
  target_text: string;           // Word ("put up with") OR Sentence ("I can't put up with this.")
  translation: string;           // Native translation
  simple_definition?: string;    // Simple definition
  context_sentence?: string;     // Context sentence from video
  context_explanation?: string;  // "Explain in context" details
  lemma?: string;
  part_of_speech?: string;
  ipa?: string;
  cefr_level?: CEFRLevel;
  video_id: string;
  video_timestamp_sec: number;
  r2_cache_hash?: string;
}

export interface RevenueCatWebhookBody {
  api_version: string;
  event: {
    id: string;
    type: 'INITIAL_PURCHASE' | 'RENEWAL' | 'CANCELLATION' | 'EXPIRATION' | 'PRODUCT_CHANGE';
    app_user_id: string; // Supabase user UUID
    original_app_user_id: string;
    product_id: string;
    period_type: 'TRIAL' | 'NORMAL' | 'INTRO';
    purchased_at_ms: number;
    expiration_at_ms: number | null;
    entitlement_ids: string[];
    store: 'APP_STORE' | 'PLAY_STORE' | 'PROMOTIONAL';
  };
}

export const CEFRLevelSchema = z.enum(['A1', 'A2', 'B1', 'B2', 'C1', 'C2']);

export const TranslationResponseSchema = z.object({
  hash: z.string().length(64),
  target_language: z.string().min(2),
  selected_text: z.string().min(1),
  lemma: z.string().min(1),
  part_of_speech: z.string().min(1),
  ipa: z.string().min(1),
  cefr_level: CEFRLevelSchema,
  simple_definition: z.string().min(1),
  contextual_translation: z.string().min(1),
  sentence_translation: z.string().min(1),
  context_explanation: z.string().min(1),
  example_sentence_en: z.string().min(1),
  example_sentence_native: z.string().min(1),
  created_at: z.string(),
});

export const TranslateRequestBodySchema = z.object({
  word: z.string().trim().min(1, 'Word is required'),
  sentence: z.string().trim().min(1, 'Context sentence is required'),
  targetLang: z.string().trim().min(2).default('en'),
  videoId: z.string().optional(),
  userId: z.string().optional(),
});

export const SubtitleCueSchema = z.object({
  id: z.string(),
  start: z.number().nonnegative(),
  duration: z.number().nonnegative(),
  end: z.number().nonnegative(),
  text: z.string(),
  tokens: z.array(z.string()),
});

export const CaptionsResponseSchema = z.object({
  videoId: z.string(),
  language: z.string(),
  isAutoGenerated: z.boolean(),
  cues: z.array(SubtitleCueSchema),
});

export const CreateFlashcardRequestBodySchema = z.object({
  type: z.enum(['word', 'sentence']),
  target_text: z.string().min(1),
  translation: z.string().min(1),
  simple_definition: z.string().optional(),
  context_sentence: z.string().optional(),
  context_explanation: z.string().optional(),
  lemma: z.string().optional(),
  part_of_speech: z.string().optional(),
  ipa: z.string().optional(),
  cefr_level: CEFRLevelSchema.optional(),
  video_id: z.string().min(1),
  video_timestamp_sec: z.number().nonnegative(),
  r2_cache_hash: z.string().optional(),
});

