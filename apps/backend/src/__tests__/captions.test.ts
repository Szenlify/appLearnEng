import { afterEach, beforeEach, describe, expect, it } from 'bun:test';
import { app } from '../index';
import { tokenizeSentence, YouTubeCaptionsService } from '../services/captions.service';

describe('Stage 2: YouTubeCaptionsService & GET /api/v1/captions', () => {
  const originalFetch = globalThis.fetch;

  afterEach(() => {
    globalThis.fetch = originalFetch;
  });

  describe('tokenizeSentence', () => {
    it('tokenizes "I can\'t put up with this!" preserving apostrophes and punctuation tokens', () => {
      const tokens = tokenizeSentence("I can't put up with this!");
      expect(tokens).toEqual(['I', "can't", 'put', 'up', 'with', 'this!']);
    });

    it('normalizes typographic apostrophes (’ -> \') and filters out empty or non-alphanumeric tokens', () => {
      const tokens = tokenizeSentence('   We   don’t   give   up ...   —   ever!  ');
      expect(tokens).toEqual(['We', "don't", 'give', 'up', 'ever!']);
    });
  });

  describe('parseTimedTextXml', () => {
    it('parses timedtext XML into SubtitleCue[] with accurate start, duration, and end timestamps', () => {
      const service = new YouTubeCaptionsService();
      const sampleXml = `<?xml version="1.0" encoding="utf-8" ?>
        <transcript>
          <text start="14.25" dur="2.4">I can&#39;t put up with this attitude.</text>
          <text start="16.65" dur="3.15">We need &quot;better&quot; &amp; faster solutions\nright now!</text>
        </transcript>`;

      const cues = service.parseTimedTextXml(sampleXml);

      expect(cues).toHaveLength(2);
      expect(cues[0]).toEqual({
        id: 'cue_0',
        start: 14.25,
        duration: 2.4,
        end: 16.65,
        text: "I can't put up with this attitude.",
        tokens: ['I', "can't", 'put', 'up', 'with', 'this', 'attitude.'],
      });

      expect(cues[1]).toEqual({
        id: 'cue_1',
        start: 16.65,
        duration: 3.15,
        end: 19.8,
        text: 'We need "better" & faster solutions right now!',
        tokens: ['We', 'need', '"better"', 'faster', 'solutions', 'right', 'now!'],
      });
    });
  });

  describe('getCaptions & GET /api/v1/captions error and success handling', () => {
    it('returns CaptionsResponse via GET /api/v1/captions?videoId=XYZ&lang=en when English captions exist', async () => {
      const mockPlayerResponse = {
        captions: {
          playerCaptionsTracklistRenderer: {
            captionTracks: [
              {
                baseUrl: 'https://www.youtube.com/api/timedtext?v=XYZ&lang=en',
                languageCode: 'en',
                vssId: '.en',
              },
            ],
          },
        },
      };

      const mockXml = `<?xml version="1.0" encoding="utf-8" ?><transcript><text start="1.5" dur="2.25">Hello world!</text></transcript>`;

      globalThis.fetch = (async (input: RequestInfo | URL) => {
        const url = String(input);
        if (url.includes('youtube.com/watch')) {
          return new Response(
            `<script>var ytInitialPlayerResponse = ${JSON.stringify(mockPlayerResponse)};</script>`,
            { status: 200 }
          );
        }
        return new Response(mockXml, { status: 200 });
      }) as typeof fetch;

      const res = await app.request('/api/v1/captions?videoId=XYZ&lang=en');
      expect(res.status).toBe(200);

      const data: any = await res.json();
      expect(data.videoId).toBe('XYZ');
      expect(data.language).toBe('en');
      expect(data.isAutoGenerated).toBe(false);
      expect(data.cues).toHaveLength(1);
      expect(data.cues[0]).toEqual({
        id: 'cue_0',
        start: 1.5,
        duration: 2.25,
        end: 3.75,
        text: 'Hello world!',
        tokens: ['Hello', 'world!'],
      });
    });

    it('throws NO_CAPTIONS_AVAILABLE and returns HTTP 422 when video has no English subtitles', async () => {
      const mockNoEnglishResponse = {
        captions: {
          playerCaptionsTracklistRenderer: {
            captionTracks: [
              {
                baseUrl: 'https://www.youtube.com/api/timedtext?v=NO_EN&lang=fr',
                languageCode: 'fr',
                vssId: '.fr',
              },
            ],
          },
        },
      };

      globalThis.fetch = (async () => {
        return new Response(
          `<script>var ytInitialPlayerResponse = ${JSON.stringify(mockNoEnglishResponse)};</script>`,
          { status: 200 }
        );
      }) as typeof fetch;

      const service = new YouTubeCaptionsService();
      await expect(service.getCaptions('NO_EN')).rejects.toThrow('NO_CAPTIONS_AVAILABLE');

      const res = await app.request('/api/v1/captions?videoId=NO_EN&lang=en');
      expect(res.status).toBe(422);

      const body: any = await res.json();
      expect(body.code).toBe('NO_CAPTIONS_AVAILABLE');
    });
  });
});
