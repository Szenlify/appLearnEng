import type { CaptionsResponse, SubtitleCue } from '@learneng/shared';

/**
 * Resolves the backend API URL.
 * When running on a physical phone in Expo Go, `localhost` would point to the phone itself,
 * so we automatically substitute the LAN IP of the development machine from Expo's hostUri.
 */
export function getApiBaseUrl(): string {
  const configured = process.env.EXPO_PUBLIC_API_URL || 'http://localhost:3000';
  if (!configured.includes('localhost') && !configured.includes('127.0.0.1')) {
    return configured.replace(/\/$/, '');
  }

  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const ConstantsModule = require('expo-constants');
    const Constants = ConstantsModule?.default || ConstantsModule;
    const hostUri: string | undefined =
      Constants?.expoConfig?.hostUri ||
      Constants?.manifest2?.extra?.expoGo?.debuggerHost ||
      Constants?.manifest?.debuggerHost;

    if (hostUri) {
      const lanHost = hostUri.split(':')[0];
      if (lanHost && lanHost !== 'localhost' && lanHost !== '127.0.0.1') {
        return configured
          .replace('localhost', lanHost)
          .replace('127.0.0.1', lanHost)
          .replace(/\/$/, '');
      }
    }
  } catch {
    // Ignore in test environments
  }

  return configured.replace(/\/$/, '');
}

function decodeHtmlEntities(input: string): string {
  return input
    .replace(/&amp;/g, '&')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(Number(dec)))
    .replace(/\n/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function tokenizeText(sentence: string): string[] {
  return sentence
    .replace(/[‘’]/g, "'")
    .split(/\s+/)
    .map((t) => t.trim())
    .filter((t) => /[a-zA-Z0-9]/.test(t));
}

function parseTimedTextXmlRegex(xmlContent: string): SubtitleCue[] {
  const cues: SubtitleCue[] = [];
  const textRegex = /<text\s+[^>]*start="([^"]+)"[^>]*dur="([^"]+)"[^>]*>([\s\S]*?)<\/text>/g;
  let match: RegExpExecArray | null;
  let idx = 0;

  while ((match = textRegex.exec(xmlContent)) !== null) {
    const start = parseFloat(match[1] || '0');
    const duration = parseFloat(match[2] || '0');
    const end = Number((start + duration).toFixed(2));
    const rawText = decodeHtmlEntities(match[3].replace(/<[^>]+>/g, ''));
    if (rawText.length > 0) {
      cues.push({
        id: `cue_${idx++}`,
        start,
        duration,
        end,
        text: rawText,
        tokens: tokenizeText(rawText),
      });
    }
  }

  for (let i = 0; i < cues.length - 1; i++) {
    if (cues[i].end > cues[i + 1].start && cues[i + 1].start > cues[i].start) {
      cues[i].end = cues[i + 1].start;
      cues[i].duration = Number((cues[i].end - cues[i].start).toFixed(2));
    }
  }

  return cues;
}

const IOS_YOUTUBE_USER_AGENT =
  'com.google.ios.youtube/20.10.4 (iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X;)';

/**
 * Direct on-device fallback for fetching YouTube English captions via InnerTube iOS API
 * when running in Expo Go without the local backend server reachable.
 */
export async function fetchYouTubeCaptionsDirect(videoId: string): Promise<CaptionsResponse> {
  const playerRes = await fetch('https://www.youtube.com/youtubei/v1/player?prettyPrint=false', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'User-Agent': IOS_YOUTUBE_USER_AGENT,
      'Accept-Language': 'en-US,en;q=0.9',
    },
    body: JSON.stringify({
      context: {
        client: {
          clientName: 'IOS',
          clientVersion: '20.10.4',
          deviceMake: 'Apple',
          deviceModel: 'iPhone16,2',
          osName: 'iPhone',
          osVersion: '18.3.2.22D82',
          hl: 'en',
          gl: 'US',
        },
      },
      videoId,
    }),
  });

  if (!playerRes.ok) {
    throw new Error('FAILED_TO_LOAD_CAPTIONS');
  }

  const data: any = await playerRes.json();
  const captionTracks: any[] =
    data?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];

  if (!captionTracks.length) {
    throw new Error('NO_CAPTIONS_AVAILABLE');
  }

  let selectedTrack = captionTracks.find(
    (t: any) =>
      (t.languageCode === 'en' || t.languageCode?.startsWith('en-')) &&
      !t.vssId?.startsWith('a.') &&
      t.kind !== 'asr'
  );
  let isAutoGenerated = false;

  if (!selectedTrack) {
    selectedTrack = captionTracks.find(
      (t: any) =>
        t.languageCode === 'en' ||
        t.languageCode?.startsWith('en-') ||
        t.vssId?.includes('.en')
    );
    isAutoGenerated = true;
  }

  if (!selectedTrack) {
    throw new Error('NO_CAPTIONS_AVAILABLE');
  }

  const xmlRes = await fetch(selectedTrack.baseUrl, {
    headers: {
      'User-Agent': IOS_YOUTUBE_USER_AGENT,
    },
  });
  const xml = await xmlRes.text();
  const cues = parseTimedTextXmlRegex(xml);

  if (cues.length === 0) {
    throw new Error('NO_CAPTIONS_AVAILABLE');
  }

  return {
    videoId,
    cues,
    language: selectedTrack.languageCode || 'en',
    isAutoGenerated,
  };
}
